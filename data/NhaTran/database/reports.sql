UPDATE posts p
SET comment_count = sub.cnt
FROM (
    SELECT post_id, COUNT(*) AS cnt
    FROM comments
    WHERE deleted_at IS NULL
    GROUP BY post_id
) sub
WHERE p.id = sub.post_id;


UPDATE posts p
SET reaction_count = sub.cnt
FROM (
    SELECT post_id, COUNT(*) AS cnt
    FROM reactions
    GROUP BY post_id
) sub
WHERE p.id = sub.post_id;


UPDATE posts p
SET bookmark_count = sub.cnt
FROM (
    SELECT post_id, COUNT(*) AS cnt
    FROM bookmarks
    GROUP BY post_id
) sub
WHERE p.id = sub.post_id;


UPDATE posts p
SET report_count = sub.cnt
FROM (
    SELECT target_id AS post_id, COUNT(*) AS cnt
    FROM reports
    WHERE target_type = 'POST'
    GROUP BY target_id
) sub
WHERE p.id = sub.post_id;
